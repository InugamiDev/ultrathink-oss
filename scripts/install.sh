add('UserPromptSubmit', 'ut:adapter:prompt-submit', 'UltraThink: manifest-backed prompt-submit hooks', null, cmd('UserPromptSubmit'), 15000);
add('PreToolUse', 'ut:adapter:pre-tool-use', 'UltraThink: manifest-backed pre-tool hooks', null, cmd('PreToolUse'), 15000);
add('PostToolUse', 'ut:adapter:post-tool-use', 'UltraThink: manifest-backed post-tool hooks', null, cmd('PostToolUse'), 60000);
add('PreCompact', 'ut:adapter:pre-compact', 'UltraThink: manifest-backed pre-compact hooks', null, cmd('PreCompact'), 15000);
add('Stop', 'ut:adapter:stop', 'UltraThink: manifest-backed stop hooks', null, cmd('Stop'), 70000);

fs.writeFileSync(settingsPath, JSON.stringify(s, null, 2) + '\n');
